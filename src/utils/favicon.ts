/**
 * Updates the browser favicon dynamically in real time to match the active theme.
 * Uses an SVG Data URI to bypass aggressive browser icon caching and ensure instant live updates.
 */
export const updateThemeFavicon = (theme: ThemeId): void => {
  if (typeof document === 'undefined') return;

  const svgContent = THEME_FAVICONS[theme] || THEME_FAVICONS.arcade;
  const dataUri = `data:image/svg+xml;utf8,${encodeURIComponent(svgContent)}`;

  // Update or create SVG favicon link
  let link = document.querySelector("link[rel~='icon']") as HTMLLinkElement | null;
  if (!link) {
    link = document.createElement('link');
    link.rel = 'icon';
    link.type = 'image/svg+xml';
    document.head.appendChild(link);
  }
  link.type = 'image/svg+xml';
  link.href = dataUri;

  // Also update alternate link if present
  const altLink = document.querySelector("link[rel='alternate icon']") as HTMLLinkElement | null;
  if (altLink) {
    altLink.href = `/favicon-${theme}.svg`;
  }
};
